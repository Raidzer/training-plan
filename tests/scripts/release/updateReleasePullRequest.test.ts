import { beforeEach, describe, expect, it, vi } from "vitest";
import { updateReleasePullRequest } from "@/scripts/release/updateReleasePullRequest.mjs";
import { generateReleaseNotes } from "@/scripts/release/generateReleaseNotes.mjs";

vi.mock("@/scripts/release/generateReleaseNotes.mjs", () => ({
  generateReleaseNotes: vi.fn(),
}));

const MAIN_SHA = "a".repeat(40);
const HEAD_SHA = "b".repeat(40);
const REPOSITORY = { owner: "Raidzer", repo: "training-plan" };
const OLD_NOTES = "### Новое\n\n- **diary:** добавлен дневник ([abcdef1](url)).";
const NEW_NOTES = "### Новое\n\n- добавлен дневник";
const HISTORY = `\n\n## 1.3.0\n\n${OLD_NOTES}\n`;
const CHANGELOG = `# История изменений\n\n## [1.4.0](url) (2026-11-17)\n\n${OLD_NOTES}${HISTORY}`;
const BODY_PREFIX = "Релиз подготовлен ботом.\n\n---\n\n## [1.4.0](url) (2026-11-17)\n\n";
const BODY_SUFFIX = "\n\n---\n\nGenerated by Release Please.";
const CONFIG = {
  "bootstrap-sha": "c".repeat(40),
  "changelog-sections": [{ type: "feat", section: "Новое", hidden: false }],
};

function createGithubMock(
  changelog = CHANGELOG,
  body: string | null = `${BODY_PREFIX}${OLD_NOTES}${BODY_SUFFIX}`
) {
  return {
    paginate: vi.fn().mockResolvedValue([]),
    rest: {
      pulls: {
        list: vi.fn(),
        get: vi.fn().mockResolvedValue({
          data: {
            number: 173,
            state: "open",
            merged_at: null,
            labels: [{ name: "autorelease: pending" }],
            body,
            head: {
              sha: HEAD_SHA,
              ref: "release-please--branches--main",
              repo: { full_name: "Raidzer/training-plan" },
            },
            base: { ref: "main", sha: MAIN_SHA, repo: { full_name: "Raidzer/training-plan" } },
          },
        }),
        update: vi.fn().mockResolvedValue({ data: {} }),
      },
      repos: {
        getContent: vi.fn().mockImplementation(({ path }: { path: string }) =>
          Promise.resolve({
            data: {
              type: "file",
              encoding: "base64",
              sha: path === "src/releases/CHANGELOG.md" ? "changelog-blob" : "manifest-blob",
              content: Buffer.from(
                path === "src/releases/CHANGELOG.md" ? changelog : '{".": "1.4.0"}'
              ).toString("base64"),
            },
          })
        ),
        createOrUpdateFileContents: vi.fn().mockResolvedValue({ data: {} }),
      },
    },
  };
}

function update(github: ReturnType<typeof createGithubMock>, overrides = {}) {
  return updateReleasePullRequest({
    github,
    ...REPOSITORY,
    sha: MAIN_SHA,
    pullRequestNumber: 173,
    config: CONFIG,
    manifest: { ".": "1.3.0" },
    ...overrides,
  });
}

function expectNoWrites(github: ReturnType<typeof createGithubMock>) {
  expect(github.rest.repos.createOrUpdateFileContents).not.toHaveBeenCalled();
  expect(github.rest.pulls.update).not.toHaveBeenCalled();
}

beforeEach(() => {
  vi.mocked(generateReleaseNotes).mockReset().mockResolvedValue(NEW_NOTES);
});

describe("updateReleasePullRequest", () => {
  it("находит pending PR при повторе без номера из release-please-action", async () => {
    const github = createGithubMock();
    const { data: pending } = await github.rest.pulls.get();
    github.rest.pulls.get.mockClear();
    github.paginate.mockResolvedValue([
      { ...pending, number: 171, labels: [{ name: "autorelease: tagged" }] },
      { ...pending, number: 172, head: { ...pending.head, repo: { full_name: "someone/fork" } } },
      pending,
    ]);

    await update(github, { pullRequestNumber: undefined });

    expect(github.paginate).toHaveBeenCalledWith(github.rest.pulls.list, {
      ...REPOSITORY,
      state: "open",
      base: "main",
      per_page: 100,
    });
    expect(github.rest.pulls.get).toHaveBeenCalledWith({ ...REPOSITORY, pull_number: 173 });
    expect(github.rest.pulls.update).toHaveBeenCalledWith({
      ...REPOSITORY,
      pull_number: 173,
      body: `${BODY_PREFIX}${NEW_NOTES}${BODY_SUFFIX}`,
    });
  });

  it("завершает подготовку без записей, если pending PR нет", async () => {
    const github = createGithubMock();

    await update(github, { pullRequestNumber: undefined });

    expect(github.rest.pulls.get).not.toHaveBeenCalled();
    expect(generateReleaseNotes).not.toHaveBeenCalled();
    expectNoWrites(github);
  });

  it("отклоняет несколько pending PR до чтения файлов и записей", async () => {
    const github = createGithubMock();
    const { data: pending } = await github.rest.pulls.get();
    github.rest.pulls.get.mockClear();
    github.paginate.mockResolvedValue([pending, { ...pending, number: 174 }]);

    await expect(update(github, { pullRequestNumber: undefined })).rejects.toThrow(
      /несколько|одного/i
    );

    expect(github.rest.pulls.get).not.toHaveBeenCalled();
    expect(github.rest.repos.getContent).not.toHaveBeenCalled();
    expectNoWrites(github);
  });

  it("не скрывает ошибку поиска pending PR", async () => {
    const github = createGithubMock();
    const error = new Error("Нет доступа к PR");
    github.paginate.mockRejectedValue(error);

    await expect(update(github, { pullRequestNumber: undefined })).rejects.toBe(error);

    expectNoWrites(github);
  });

  it("не обновляет PR для более свежего main из старого запуска CI", async () => {
    const github = createGithubMock();
    const { data: pending } = await github.rest.pulls.get();
    pending.base.sha = "d".repeat(40);

    await expect(update(github)).rejects.toThrow(/SHA|main|устарел/i);

    expect(github.rest.repos.getContent).not.toHaveBeenCalled();
    expect(generateReleaseNotes).not.toHaveBeenCalled();
    expectNoWrites(github);
  });

  it("обновляет только новую версию и тот же фрагмент body по blob SHA релизной ветки", async () => {
    const github = createGithubMock();

    await update(github);

    expect(github.rest.pulls.get).toHaveBeenCalledWith({
      ...REPOSITORY,
      pull_number: 173,
    });
    expect(github.rest.repos.getContent.mock.calls).toEqual([
      [{ ...REPOSITORY, path: "src/releases/CHANGELOG.md", ref: HEAD_SHA }],
      [{ ...REPOSITORY, path: ".release-please-manifest.json", ref: HEAD_SHA }],
    ]);
    expect(generateReleaseNotes).toHaveBeenCalledWith({
      github,
      ...REPOSITORY,
      base: "v1.3.0",
      head: MAIN_SHA,
      sections: CONFIG["changelog-sections"],
    });
    expect(github.rest.repos.createOrUpdateFileContents).toHaveBeenCalledOnce();
    const fileUpdate = github.rest.repos.createOrUpdateFileContents.mock.calls[0][0];
    expect(fileUpdate).toMatchObject({
      ...REPOSITORY,
      path: "src/releases/CHANGELOG.md",
      sha: "changelog-blob",
      branch: "release-please--branches--main",
      message: expect.stringMatching(/^chore\(release\): /),
    });
    expect(Buffer.from(fileUpdate.content, "base64").toString("utf8")).toBe(
      `# История изменений\n\n## [1.4.0](url) (2026-11-17)\n\n${NEW_NOTES}${HISTORY}`
    );
    expect(github.rest.pulls.update).toHaveBeenCalledWith({
      ...REPOSITORY,
      pull_number: 173,
      body: `${BODY_PREFIX}${NEW_NOTES}${BODY_SUFFIX}`,
    });
  });

  it("не пишет файл и body повторно, когда они уже содержат подготовленный текст", async () => {
    const github = createGithubMock(
      `# История изменений\n\n## 1.4.0\n\n${NEW_NOTES}${HISTORY}`,
      `${BODY_PREFIX}${NEW_NOTES}${BODY_SUFFIX}`
    );

    await update(github);

    expectNoWrites(github);
  });

  it("после сбоя записи body завершает обновление без нового коммита changelog", async () => {
    const github = createGithubMock(`# История изменений\n\n## 1.4.0\n\n${NEW_NOTES}${HISTORY}`);

    await update(github);

    expect(github.rest.repos.createOrUpdateFileContents).not.toHaveBeenCalled();
    expect(github.rest.pulls.update).toHaveBeenCalledWith({
      ...REPOSITORY,
      pull_number: 173,
      body: `${BODY_PREFIX}${NEW_NOTES}${BODY_SUFFIX}`,
    });
  });

  it("сохраняет готовый body при обновлении оставшегося changelog", async () => {
    const github = createGithubMock(CHANGELOG, `${BODY_PREFIX}${NEW_NOTES}${BODY_SUFFIX}`);

    await update(github);

    expect(github.rest.repos.createOrUpdateFileContents).toHaveBeenCalledOnce();
    expect(github.rest.pulls.update).not.toHaveBeenCalled();
  });

  it("сохраняет details и summary Release Please вокруг описания", async () => {
    const prefix =
      "Релиз.\n---\n\n<details><summary>training-plan: 1.4.0</summary>\n\n## 1.4.0\n\n";
    const suffix = `\n</details>${BODY_SUFFIX}`;
    const github = createGithubMock(CHANGELOG, `${prefix}${OLD_NOTES}${suffix}`);

    await update(github);

    expect(github.rest.pulls.update).toHaveBeenCalledWith({
      ...REPOSITORY,
      pull_number: 173,
      body: `${prefix}${NEW_NOTES}${suffix}`,
    });
  });

  it.each([
    [{ ...CONFIG, "last-release-sha": "d".repeat(40) }, { ".": "1.3.0" }, "d".repeat(40)],
    [CONFIG, {}, "c".repeat(40)],
  ])("выбирает явную или первоначальную границу релиза", async (config, manifest, base) => {
    const github = createGithubMock();

    await update(github, { config, manifest });

    expect(generateReleaseNotes).toHaveBeenCalledWith(expect.objectContaining({ base }));
  });

  it("сохраняет CRLF, заголовок и прежнюю историю changelog", async () => {
    const github = createGithubMock(CHANGELOG.replaceAll("\n", "\r\n"));

    await update(github);

    const fileUpdate = github.rest.repos.createOrUpdateFileContents.mock.calls[0][0];
    expect(Buffer.from(fileUpdate.content, "base64").toString("utf8")).toBe(
      `# История изменений\n\n## [1.4.0](url) (2026-11-17)\n\n${NEW_NOTES}${HISTORY}`.replaceAll(
        "\n",
        "\r\n"
      )
    );
  });

  it("не заменяет совпадающий текст до заголовка новой версии", async () => {
    const introduction = `# История изменений\n\n${OLD_NOTES}\n\n`;
    const github = createGithubMock(`${introduction}## 1.4.0\n\n${OLD_NOTES}${HISTORY}`);

    await update(github);

    const fileUpdate = github.rest.repos.createOrUpdateFileContents.mock.calls[0][0];
    expect(Buffer.from(fileUpdate.content, "base64").toString("utf8")).toBe(
      `${introduction}## 1.4.0\n\n${NEW_NOTES}${HISTORY}`
    );
  });

  it.each([
    null,
    "Body без описания",
    `${BODY_PREFIX}${OLD_NOTES}\n\n${OLD_NOTES}${BODY_SUFFIX}`,
    `${BODY_PREFIX}${OLD_NOTES}`,
    `${BODY_PREFIX}### Новое\n\n- Другой текст${BODY_SUFFIX}`,
  ])("отклоняет отсутствующий или неоднозначный фрагмент body до записей", async (body) => {
    const github = createGithubMock(CHANGELOG, body);

    await expect(update(github)).rejects.toThrow(/body|тел[оеа]|фрагмент/i);

    expectNoWrites(github);
  });

  it.each(["# История изменений", "## 1.4.0\n", "## 1.4.0\n- Один\n## 1.4.0\n- Два"])(
    "отклоняет отсутствующую, пустую или дублированную новую версию до записей",
    async (changelog) => {
      const github = createGithubMock(changelog);

      await expect(update(github)).rejects.toThrow(/1\.4\.0/);

      expectNoWrites(github);
    }
  );

  it("отклоняет manifest без новой версии, чтобы не менять прошлый релиз", async () => {
    const github = createGithubMock();

    await expect(update(github, { manifest: { ".": "1.4.0" } })).rejects.toThrow(/верси|manifest/i);

    expectNoWrites(github);
  });

  it.each(["closed", "fork", "base"])(
    "не изменяет неподходящий релизный PR: %s",
    async (scenario) => {
      const github = createGithubMock();
      const { data: pullRequest } = await github.rest.pulls.get();

      if (scenario === "closed") {
        pullRequest.state = "closed";
      } else if (scenario === "fork") {
        pullRequest.head.repo.full_name = "someone/fork";
      } else {
        pullRequest.base.ref = "develop";
      }

      await expect(update(github)).rejects.toThrow(/PR|репозитори|main/);

      expectNoWrites(github);
    }
  );

  it.each([
    { type: "dir" },
    { type: "file", encoding: "none", sha: "blob", content: "" },
    { type: "file", encoding: "base64", content: "" },
  ])("отклоняет ответ API без содержимого файла или blob SHA", async (data) => {
    const github = createGithubMock();
    github.rest.repos.getContent.mockResolvedValue({ data });

    await expect(update(github)).rejects.toThrow(/файл|blob|SHA/i);

    expectNoWrites(github);
  });

  it("не записывает ничего при ошибке генерации", async () => {
    const github = createGithubMock();
    const error = new Error("Нет пунктов нового релиза");
    vi.mocked(generateReleaseNotes).mockRejectedValue(error);

    await expect(update(github)).rejects.toBe(error);

    expectNoWrites(github);
  });

  it.each([
    "pulls.get",
    "repos.getContent",
    "repos.createOrUpdateFileContents",
    "pulls.update",
  ] as const)("не скрывает ошибку API %s", async (method) => {
    const github = createGithubMock();
    const error = new Error(`Ошибка ${method}`);
    const requests = {
      "pulls.get": github.rest.pulls.get,
      "repos.getContent": github.rest.repos.getContent,
      "repos.createOrUpdateFileContents": github.rest.repos.createOrUpdateFileContents,
      "pulls.update": github.rest.pulls.update,
    };
    requests[method].mockRejectedValue(error);

    await expect(update(github)).rejects.toBe(error);

    if (method !== "pulls.update") {
      expect(github.rest.pulls.update).not.toHaveBeenCalled();
    }
  });
});
