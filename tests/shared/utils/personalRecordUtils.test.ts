import { describe, expect, it } from "vitest";
import {
  getPersonalRecordDistanceKey,
  parsePersonalRecordTime,
} from "@/shared/utils/personalRecordUtils";

describe("getPersonalRecordDistanceKey", () => {
  it.each([
    ["Марафон", "marathon"],
    ["21,1 км", "21_1k"],
    ["10 км", "10k"],
    ["5 км", "5k"],
    ["3 км", "3k"],
    ["1,5 км", "1_5k"],
    ["1 км", "1k"],
    ["800 м", "800m"],
    ["400 м", "400m"],
    ["200 м", "200m"],
    ["100 м", "100m"],
  ])("распознаёт дистанцию каталога %s", (value, expected) => {
    expect(getPersonalRecordDistanceKey(value)).toBe(expected);
  });

  it.each([
    ["  МАРАФОН  ", "marathon"],
    ["42195м", "marathon"],
    ["42.195 km", "marathon"],
    ["42,195КМ", "marathon"],
    ["21100 m", "21_1k"],
    ["21.1k", "21_1k"],
    ["21097.5 м", "21_1k"],
    ["21097,5m", "21_1k"],
    ["21,0975 км", "21_1k"],
    ["21.0975KM", "21_1k"],
    ["10000 M", "10k"],
    [" 5 K ", "5k"],
    ["5,000 km", "5k"],
    ["0005,0000 km", "5k"],
    ["3000м", "3k"],
    ["1 500 M", "1_5k"],
    ["1000m", "1k"],
    ["0.8km", "800m"],
    ["0,4KM", "400m"],
    ["0.2k", "200m"],
    ["0,1 км", "100m"],
  ])("сопоставляет точную длину %s", (value, expected) => {
    expect(getPersonalRecordDistanceKey(value)).toBe(expected);
  });

  it.each([
    "",
    "   ",
    "5",
    "5000",
    "0км",
    "-5км",
    "+5км",
    "5e3м",
    "5E0км",
    "0x1388м",
    "NaNкм",
    "Infinityм",
    "4999,6м",
    "5000.1m",
    "4.9996km",
    "5.0000000000000001km",
    "4999.9999999999999m",
    "21.0975000000000000001km",
    "21097м",
    "21.097km",
    "42195.1m",
    "10 км трейл",
    "около 5 км",
    "Марафон трейл",
    "Полумарафон",
    "5 miles",
    "5..0км",
    ".5км",
    "5,км",
    "50000км",
  ])("не сопоставляет невалидную или нестандартную дистанцию %s", (value) => {
    expect(getPersonalRecordDistanceKey(value)).toBeNull();
  });
});

describe("parsePersonalRecordTime", () => {
  it.each([
    ["39:30", "00:39:30", 237000],
    ["00:39:30", "00:39:30", 237000],
    ["00:39:30.00", "00:39:30", 237000],
    ["39:30,00", "00:39:30", 237000],
    ["39:30.1", "00:39:30.10", 237010],
    ["39:30.10", "00:39:30.10", 237010],
    ["00:39:30,1", "00:39:30.10", 237010],
    ["03:04.01", "00:03:04.01", 18401],
    ["01:02:03.45", "01:02:03.45", 372345],
    [" 02:03:04,05 ", "02:03:04.05", 738405],
    ["00:00.01", "00:00:00.01", 1],
    ["00:00:00.1", "00:00:00.10", 10],
    ["00:01", "00:00:01", 100],
    ["59:59.99", "00:59:59.99", 359999],
    ["99:59:59.99", "99:59:59.99", 35999999],
  ])("разбирает %s в нормализованный формат и целые сотые", (value, timeText, hundredths) => {
    expect(parsePersonalRecordTime(value)).toEqual({ timeText, hundredths });
  });

  it.each([
    "",
    "   ",
    "DNF",
    "00:00",
    "00:00.0",
    "00:00:00.00",
    "00:00,00",
    "60:00",
    "00:60:00",
    "00:00:60",
    "12:60",
    "1:02",
    "01:2",
    "1:02:03",
    "100:00:00",
    "-01:02",
    "+01:02",
    "01:02.",
    "01:02.123",
    "01:02,123",
    "01:02.1.2",
    "01: 02",
    "01:02:03:04",
    "01:02 DNF",
  ])("отклоняет нулевое или невалидное время %s", (value) => {
    expect(parsePersonalRecordTime(value)).toBeNull();
  });
});
